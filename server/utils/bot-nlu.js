// server/utils/bot-nlu.js — F3.71: чистый классификатор намерений бота (без БД и сети).
// Регулярки вынесены из server/routes/tg.js без изменения формулировок — поведение прежнее,
// но логику можно покрыть юнит-тестами (tests/bot-copy.spec.mjs) без поднятия сервера.
export function botIntent(rawText) {
  const t = String(rawText || '').toLowerCase();
  if (/(оператор|человек|помощь|поддержк|админ|связаться|проблем|жалоб|ошибк|позови)/i.test(t)) return 'support';
  if (/(штамп|бонус|бесплатн|подарок|зерн|зёрн|промокод|баллы|qr)/i.test(t)) return 'bonus';
  if (/(заказ|где курьер|где доставка|доставк|статус заказа)/i.test(t)) return 'orders';
  if (/(где вы|адрес|находит|как добраться|время работ|режим работ|часы работ|до скольки|со скольки|янтарн)/i.test(t)) return 'address';
  if (/(меню|пицц|ролл|кофе|напитк|десерт)/i.test(t)) return 'menu';
  return null;
}
